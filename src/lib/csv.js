export function parseCSV(text) {
  const rows = []
  let row = []
  let field = ''
  let inQuotes = false

  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (inQuotes) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"'
          i++
        } else {
          inQuotes = false
        }
      } else {
        field += c
      }
    } else if (c === '"') {
      inQuotes = true
    } else if (c === ',') {
      row.push(field)
      field = ''
    } else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++
      row.push(field)
      field = ''
      rows.push(row)
      row = []
    } else {
      field += c
    }
  }
  if (field.length > 0 || row.length > 0) {
    row.push(field)
    rows.push(row)
  }

  const filtered = rows.filter((r) => r.some((cell) => cell.trim() !== ''))
  if (filtered.length === 0) return []

  const header = filtered[0].map((h) => h.trim().toLowerCase())
  return filtered.slice(1).map((r) => {
    const obj = {}
    header.forEach((key, i) => {
      obj[key] = (r[i] ?? '').trim()
    })
    return obj
  })
}
